#!/usr/bin/env node
// Packs the Website Modernization templates (HTML files) into a TS module the
// edge functions can import (they can't read loose files). Run after editing
// any file in supabase/functions/_shared/website-templates/:
//
//   node scripts/build-website-templates.mjs

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = new URL('../supabase/functions/_shared/website-templates/', import.meta.url).pathname;
const templates = Object.fromEntries(
  readdirSync(dir)
    .filter(f => f.endsWith('.html'))
    .map(f => [f.replace(/\.html$/, ''), readFileSync(join(dir, f), 'utf8')]),
);
const css = readFileSync(join(dir, 'partials/enquire-style.html'), 'utf8');
const script = readFileSync(join(dir, 'partials/enquire-script.html'), 'utf8');

const out = `// GENERATED by scripts/build-website-templates.mjs from the .html files in
// this folder. Do not edit; edit the .html and re-run the script.

export const TEMPLATE_SOURCES: Record<string, string> = ${JSON.stringify(templates, null, 0)};

export const ENQUIRE_CSS = ${JSON.stringify(css)};

export const ENQUIRE_SCRIPT = ${JSON.stringify(script)};
`;
writeFileSync(join(dir, 'templates.generated.ts'), out);
console.log(`Packed ${Object.keys(templates).join(', ')} into templates.generated.ts`);
